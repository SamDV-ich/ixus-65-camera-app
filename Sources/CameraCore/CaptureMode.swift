import Foundation

struct CaptureMode: Identifiable, Equatable {
    let id: Int
    let name: String
    var isPhoto: Bool { !name.uppercased().hasPrefix("VIDEO") }
    private var key: String {
        let upper = name.uppercased()
        return upper.hasPrefix("SCN_") ? String(upper.dropFirst(4)) : upper
    }
    private var details: (String, String)? {
        switch key {
        case "AUTO": return ("Авто", "Камера сама выбирает параметры съёмки.")
        case "P": return ("Программный (P)", "Выдержку и диафрагму выбирает камера. В меню Canon этот режим называется Manual: он позволяет менять дополнительные параметры, но не даёт полного ручного управления экспозицией.")
        case "PORTRAIT": return ("Портрет", "Для съёмки людей с мягкой передачей изображения.")
        case "NIGHT_SNAPSHOT": return ("Ночной портрет", "Для людей на фоне вечерней или ночной сцены. Следите за неподвижностью камеры и человека.")
        case "NIGHT_SCENE": return ("Ночная сцена", "Для съёмки ночью. На длинной выдержке камеру нужно закрепить.")
        case "KIDS_PETS": return ("Дети и животные", "Для подвижных объектов, например играющих детей и домашних животных.")
        case "INDOOR": return ("В помещении", "Для съёмки при искусственном освещении. Камера подбирает параметры для передачи цвета и уменьшения смазывания.")
        case "FOLIAGE": return ("Листва", "Для растений, цветов и осенней листвы с насыщенными цветами.")
        case "SNOW": return ("Снег", "Для людей на снежном фоне: помогает сохранить лицо светлым и уменьшить синий оттенок снега.")
        case "BEACH": return ("Пляж", "Для людей на фоне яркого песка и воды: помогает избежать слишком тёмных лиц.")
        case "FIREWORK", "FIREWORKS": return ("Фейерверк", "Для фейерверков на ночном небе. Используйте штатив: выдержка может быть длинной.")
        case "UNDERWATER": return ("Под водой", "Корректирует цвет для подводной съёмки. Камера требует отдельного водонепроницаемого бокса.")
        case "DIGITAL_MACRO": return ("Цифровое макро", "Для мелких предметов примерно в 3–10 см от объектива на широком угле. Используется цифровое увеличение с потерей детализации.")
        case "COLOR_ACCENT": return ("Акцент цветом", "Сохраняет выбранный цвет, остальные делает чёрно-белыми. Цвет выбирается в меню самой камеры.")
        case "COLOR_SWAP": return ("Замена цвета", "Заменяет выбранный цвет другим. Исходный и новый цвета задаются в меню самой камеры.")
        case "MY_COLORS": return ("Мои цвета", "Цветовые эффекты Canon. Дополнительные параметры выбираются в меню самой камеры.")
        case "STITCH": return ("Панорама", "Помогает снимать перекрывающиеся кадры для последующей склейки. Приложение сохраняет отдельные JPEG и само панораму не собирает.")
        case "LONG_SHUTTER": return ("Длинная выдержка", "Для съёмки с длительной экспозицией. Выдержка выбирается в меню камеры; используйте штатив.")
        default: return nil
        }
    }
    var title: String { details?.0 ?? name }
    var explanation: String {
        if !isPhoto { return "На камере выбран видеорежим. Запись видео этим приложением пока не поддерживается. Выберите режим фотосъёмки." }
        return (details?.1 ?? "Режим, который CHDK сообщает как доступный на подключённой камере. Подробности смотрите в инструкции Canon; отдельного описания этого режима в приложении пока нет.")
            + "\n\nДоступность вспышки и других настроек зависит от режима."
    }
}
